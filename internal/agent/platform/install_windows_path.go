//go:build windows

package platform

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
)

// shimMarker 写在 sprout.cmd 里，用来认出“这是 /install-sprout 生成的”：不是我们的文件不覆盖、不删除。
const shimMarker = "rem sprout-shim: generated by sprout /install-sprout"

// shimContent 是指向 target 的 sprout.cmd。纯 ASCII、CRLF、无 BOM；% 在 .cmd 里要写成 %%。
func shimContent(target string) string {
	return "@echo off\r\n" + shimMarker + "\r\n" +
		`"` + strings.ReplaceAll(target, "%", "%%") + `" %*` + "\r\n" +
		"exit /b %errorlevel%\r\n"
}

// ownShim 报告 shim 是否存在；存在但不是我们生成的时报错。
func ownShim(p string) (bool, error) {
	b, err := os.ReadFile(p)
	switch {
	case errors.Is(err, fs.ErrNotExist):
		return false, nil
	case err != nil:
		return false, fmt.Errorf("无法读取 %s: %w", p, err)
	case !strings.Contains(string(b), shimMarker):
		return false, fmt.Errorf("%s 已存在但不是 /install-sprout 生成的，没有动它；确认不需要后手动删除再注册", p)
	}
	return true, nil
}

// pathPlan 是注册时对用户 PATH 的改法。条目保持原样（含未展开的 %VAR%），只增删整条。
type pathPlan struct {
	entries []string
	changed bool
	removed []string // 只装着旧 sprout 的目录，已移除
	kept    []string // 也有 sprout 但还有别的程序，没有移除
}

// planInstallPath 把 binDir 放到最前面（原来就有的去重），并移除只装着旧 sprout 的目录。
// targetDir 是被注册的 exe 所在目录：它里面的 sprout 就是同一个程序，不算冲突。
func planInstallPath(old, binDir, targetDir string, expand func(string) string,
	dirInfo func(string) (hasSprout, onlySprout bool)) pathPlan {
	p := pathPlan{entries: []string{binDir}}
	if old != "" {
		for _, e := range strings.Split(old, ";") {
			x := expand(e)
			switch {
			case sameWinPath(x, binDir):
				continue
			case strings.TrimSpace(x) != "" && !sameWinPath(x, targetDir):
				if has, only := dirInfo(x); has && only {
					p.removed = append(p.removed, e)
					continue
				} else if has {
					p.kept = append(p.kept, e)
				}
			}
			p.entries = append(p.entries, e)
		}
	}
	p.changed = strings.Join(p.entries, ";") != old
	return p
}

// stripPath 从 PATH 里去掉 binDir，返回新值和是否找到过。
func stripPath(old, binDir string, expand func(string) string) (string, bool) {
	if old == "" {
		return old, false
	}
	var keep []string
	found := false
	for _, e := range strings.Split(old, ";") {
		if sameWinPath(expand(e), binDir) {
			found = true
			continue
		}
		keep = append(keep, e)
	}
	return strings.Join(keep, ";"), found
}

// sameWinPath 不区分大小写、忽略首尾空白、引号和末尾的反斜杠比较两个已展开的路径。
func sameWinPath(a, b string) bool {
	a, b = strings.Trim(strings.TrimSpace(a), `"`), strings.Trim(strings.TrimSpace(b), `"`)
	if a == "" || b == "" {
		return false
	}
	return strings.EqualFold(filepath.Clean(a), filepath.Clean(b))
}

// expandWin 展开 %VAR%；不认识的变量原样保留，和 Windows 自己的行为一致。只用于比较路径。
func expandWin(s string, lookup func(string) (string, bool)) string {
	var b strings.Builder
	for {
		i := strings.IndexByte(s, '%')
		if i < 0 {
			break
		}
		j := strings.IndexByte(s[i+1:], '%')
		if j < 0 {
			break
		}
		if v, ok := lookup(s[i+1 : i+1+j]); ok && j > 0 {
			b.WriteString(s[:i] + v)
			s = s[i+2+j:]
		} else {
			b.WriteString(s[:i+1])
			s = s[i+1:]
		}
	}
	b.WriteString(s)
	return b.String()
}

// sproutDirInfo 看 dir 里有没有 sprout 命令（任何 PATHEXT 扩展名），以及有没有别的可执行文件。
// 目录读不了（不存在、没权限）当作没有。
func sproutDirInfo(dir string, exts map[string]bool) (hasSprout, onlySprout bool) {
	ents, err := os.ReadDir(dir)
	if err != nil {
		return false, false
	}
	other := false
	for _, e := range ents {
		ext := strings.ToLower(filepath.Ext(e.Name()))
		if e.IsDir() || !exts[ext] {
			continue
		}
		if strings.EqualFold(strings.TrimSuffix(e.Name(), filepath.Ext(e.Name())), "sprout") {
			hasSprout = true
		} else {
			other = true
		}
	}
	return hasSprout, hasSprout && !other
}

// exeExts 是 PATHEXT 里的扩展名，外加 PowerShell 会从 PATH 运行的 .ps1。
func exeExts(pathext string) map[string]bool {
	if pathext == "" {
		pathext = ".COM;.EXE;.BAT;.CMD"
	}
	m := map[string]bool{".ps1": true}
	for _, e := range strings.Split(pathext, ";") {
		if e = strings.ToLower(strings.TrimSpace(e)); e != "" {
			m[e] = true
		}
	}
	return m
}

func isASCII(s string) bool {
	for i := 0; i < len(s); i++ {
		if s[i] >= 0x80 {
			return false
		}
	}
	return true
}
